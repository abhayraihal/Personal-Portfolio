// Writes src/config/glyphs.ts: the characters each in-world font can draw. Run: npm run glyphs
import fs from 'node:fs';
import opentype from 'opentype.js';

const fonts = {
  body: 'public/fonts/rubik-latin-400-normal.woff',
  bodyBold: 'public/fonts/rubik-latin-700-normal.woff',
  display: 'public/fonts/lilita-one-latin-400-normal.woff',
};

const out = {};
for (const [name, file] of Object.entries(fonts)) {
  const buf = fs.readFileSync(file);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const chars = new Set();
  for (let i = 0; i < font.glyphs.length; i++) {
    const g = font.glyphs.get(i);
    for (const u of g.unicodes ?? []) if (u >= 32) chars.add(String.fromCodePoint(u));
  }
  out[name] = [...chars].toSorted().join('');
}
const typeface = JSON.parse(fs.readFileSync('public/fonts/LilitaOne-Regular.typeface.json', 'utf8'));
out.display3d = Object.keys(typeface.glyphs).filter((c) => c.codePointAt(0) >= 32).toSorted().join('');

const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
  .join('\n');
fs.writeFileSync(
  'src/config/glyphs.ts',
  `// Generated by scripts/gen-glyphs.mjs from the font files in public/fonts. Do not edit.\n\nexport const GLYPHS = {\n${body}\n};\n\nexport type GlyphFont = keyof typeof GLYPHS;\n\nconst sets = Object.fromEntries(Object.entries(GLYPHS).map(([k, v]) => [k, new Set(v)])) as Record<GlyphFont, Set<string>>;\n\n// Characters in text that the font cannot draw (whitespace and newlines are fine).\nexport function missingGlyphs(text: string, font: GlyphFont): string[] {\n  const set = sets[font];\n  const missing = new Set<string>();\n  for (const ch of text) if (!/\\s/.test(ch) && !set.has(ch)) missing.add(ch);\n  return [...missing];\n}\n`,
);
for (const [k, v] of Object.entries(out)) console.log(k, [...v].length, 'chars; has · – — ’ → × ° ★:', ['·', '–', '—', '’', '→', '×', '°', '★'].map((c) => (v.includes(c) ? c : '_')).join(''));
